LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;

ENTITY MODULE_1 IS
  PORT (
    A_i : IN STD_LOGIC;
    B_i : IN STD_LOGIC;
    C_i : IN STD_LOGIC;
    F_o : OUT STD_LOGIC
  );
END ENTITY MODULE_1;

ARCHITECTURE behavioral OF MODULE_1 IS
BEGIN
  p_variable : PROCESS (A_i, B_i, C_i)
    VARIABLE V_v : STD_LOGIC;
  BEGIN
    V_v := A_i NAND B_i;
    V_v := V_v NOR C_i;
    F_o <= NOT V_v;
  END PROCESS p_variable;
END ARCHITECTURE behavioral;
